-- ##############################################################################
-- ## 1. ESQUEMA (tablas, restricciones, índices y vista)
-- ##############################################################################

-- ==============================================================================
-- CINECONECTA - ESQUEMA RELACIONAL (Oracle)
-- Ejecutar con el usuario asignado en el curso (SID: ESTUD).
--
-- Modelo suministrado: ACCOUNTS, PROFILES, PLANS, SUBSCRIPTIONS, PAYMENTS.
-- Se agregan restricciones, índices y vistas para cumplir las reglas del negocio.
--
-- Cambios sobre el modelo suministrado (justificación para el documento):
--   * Llaves primarias con IDENTITY: el motor genera los ids; evita colisiones
--     entre solicitudes concurrentes. No agrega ni quita columnas.
--   * CHECK en isActive ('Y'/'N'), price, maxProfiles, maxAgeRating, amount y
--     endsAt > startsAt: validan datos aun si la aplicación falla.
--   * Índices adicionales para las consultas principales (ver cada índice).
--   * Vista V_ACTIVE_SUBSCRIPTIONS: una sola definición de "suscripción vigente".
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. PLANS
-- ------------------------------------------------------------------------------
CREATE TABLE plans (
    planId       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR2(60)  NOT NULL,
    price        NUMBER(12,2)  NOT NULL,
    maxProfiles  INTEGER       NOT NULL,
    CONSTRAINT pk_plans PRIMARY KEY (planId),
    CONSTRAINT uq_plans_name UNIQUE (name),
    CONSTRAINT ck_plans_price CHECK (price > 0),
    CONSTRAINT ck_plans_maxprofiles CHECK (maxProfiles >= 1)
);

-- ------------------------------------------------------------------------------
-- 2. ACCOUNTS
-- ------------------------------------------------------------------------------
CREATE TABLE accounts (
    accountId     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fullName      VARCHAR2(150) NOT NULL,
    email         VARCHAR2(254) NOT NULL,
    passwordHash  VARCHAR2(255) NOT NULL,
    createdAt     TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (accountId)
);

-- Correo único sin distinguir mayúsculas (RF2). También acelera el login.
CREATE UNIQUE INDEX ux_accounts_email_ci ON accounts (LOWER(email));

-- ------------------------------------------------------------------------------
-- 3. PROFILES
-- isActive: 'Y' = activo, 'N' = desactivado (se conserva la actividad histórica)
-- ------------------------------------------------------------------------------
CREATE TABLE profiles (
    profileId     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    accountId     INTEGER       NOT NULL,
    name          VARCHAR2(60)  NOT NULL,
    maxAgeRating  INTEGER       NOT NULL,
    isActive      CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_profiles PRIMARY KEY (profileId),
    CONSTRAINT fk_profiles_account FOREIGN KEY (accountId) REFERENCES accounts (accountId),
    CONSTRAINT ck_profiles_active CHECK (isActive IN ('Y', 'N')),
    CONSTRAINT ck_profiles_rating CHECK (maxAgeRating >= 0)
);

-- Nombre único dentro de la cuenta, sin distinguir mayúsculas (RF8).
CREATE UNIQUE INDEX ux_profiles_name_ci ON profiles (accountId, LOWER(name));

-- Listar perfiles de la cuenta y contar los activos contra el máximo del plan
-- (RF10, RF12). Oracle no indexa las llaves foráneas automáticamente.
CREATE INDEX ix_profiles_account_active ON profiles (accountId, isActive);

-- ------------------------------------------------------------------------------
-- 4. SUBSCRIPTIONS
-- Vigencia: startsAt <= ahora < endsAt (incluye el inicio, excluye el fin).
-- ------------------------------------------------------------------------------
CREATE TABLE subscriptions (
    subscriptionId  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    accountId       INTEGER   NOT NULL,
    planId          INTEGER   NOT NULL,
    startsAt        TIMESTAMP NOT NULL,
    endsAt          TIMESTAMP NOT NULL,
    CONSTRAINT pk_subscriptions PRIMARY KEY (subscriptionId),
    CONSTRAINT fk_subs_account FOREIGN KEY (accountId) REFERENCES accounts (accountId),
    CONSTRAINT fk_subs_plan FOREIGN KEY (planId) REFERENCES plans (planId),
    CONSTRAINT ck_subs_period CHECK (endsAt > startsAt)
);

-- Verificación de vigencia (antes de buscar, abrir series y reproducir) y
-- detección de períodos superpuestos al contratar.
CREATE INDEX ix_subs_account_period ON subscriptions (accountId, startsAt, endsAt);

-- Informes por plan y llave foránea hacia PLANS.
CREATE INDEX ix_subs_plan ON subscriptions (planId);

-- ------------------------------------------------------------------------------
-- 5. PAYMENTS
-- Cada suscripción tiene exactamente un pago (UNIQUE sobre subscriptionId).
-- No se guardan los pagos rechazados.
-- ------------------------------------------------------------------------------
CREATE TABLE payments (
    paymentId       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    subscriptionId  INTEGER       NOT NULL,
    paidAt          TIMESTAMP     NOT NULL,
    amount          NUMBER(12,2)  NOT NULL,
    reference       VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (paymentId),
    CONSTRAINT fk_payments_subscription FOREIGN KEY (subscriptionId) REFERENCES subscriptions (subscriptionId),
    CONSTRAINT uq_payments_subscription UNIQUE (subscriptionId),
    CONSTRAINT uq_payments_reference UNIQUE (reference),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);

-- Informe de ingresos por plan: filtra por rango de fechas y suma montos.
CREATE INDEX ix_payments_paidat ON payments (paidAt, amount, subscriptionId);

-- ------------------------------------------------------------------------------
-- 6. VISTAS
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_active_subscriptions AS
SELECT s.subscriptionId,
       s.accountId,
       s.planId,
       p.name        AS planName,
       p.maxProfiles AS maxProfiles,
       s.startsAt,
       s.endsAt
FROM   subscriptions s
JOIN   plans p ON p.planId = s.planId
WHERE  s.startsAt <= LOCALTIMESTAMP
AND    s.endsAt   >  LOCALTIMESTAMP;


-- ##############################################################################
-- ## 2. PROCEDIMIENTO DE CONTRATACIÓN
-- ##############################################################################

-- ==============================================================================
-- PROCEDIMIENTO DE CONTRATACIÓN (pago aprobado + suscripción en UNA transacción)
--
-- La aplicación decide si el pago simulado se aprueba. Si se rechaza, NO llama
-- este procedimiento (no se guardan los intentos rechazados).
--
-- Cómo cumple las reglas:
--   * RNF10 (concurrencia): bloquea la fila de la cuenta con FOR UPDATE. Dos
--     solicitudes de la misma cuenta se ejecutan una detrás de la otra; la
--     segunda ve la suscripción de la primera y es rechazada.
--   * RNF11 (atomicidad): SAVEPOINT + ROLLBACK TO. Si falla el pago o la
--     suscripción, no queda ningún registro parcial ni el bloqueo.
--   * RF16/RF22: no permite períodos superpuestos para la cuenta.
--   * RF23: los perfiles activos no pueden superar el máximo del nuevo plan.
--
-- El procedimiento NO hace COMMIT: lo hace quien lo llama (la aplicación o la
-- prueba). Si la aplicación usa @Transactional, puede hacer este mismo flujo en
-- Java; el procedimiento sirve como referencia y para las pruebas en SQL.
--
-- Códigos de error:
--   -20001 la cuenta ya tiene una suscripción vigente o superpuesta
--   -20002 hay más perfiles activos de los que admite el nuevo plan
--   -20003 la cuenta no existe
--   -20004 el plan no existe
-- ==============================================================================
CREATE OR REPLACE PROCEDURE sp_contract_subscription (
    p_account_id      IN  accounts.accountId%TYPE,
    p_plan_id         IN  plans.planId%TYPE,
    p_reference       IN  payments.reference%TYPE,
    p_subscription_id OUT subscriptions.subscriptionId%TYPE
) AS
    v_locked    accounts.accountId%TYPE;
    v_price     plans.price%TYPE;
    v_max       plans.maxProfiles%TYPE;
    v_start     TIMESTAMP := LOCALTIMESTAMP;
    v_end       TIMESTAMP;
    v_overlaps  NUMBER;
    v_active    NUMBER;
BEGIN
    SAVEPOINT sp_contract;
    v_end := v_start + INTERVAL '30' DAY;

    -- 1. Serializar las contrataciones de esta cuenta
    BEGIN
        SELECT accountId INTO v_locked
        FROM   accounts
        WHERE  accountId = p_account_id
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20003, 'La cuenta no existe: ' || p_account_id);
    END;

    -- 2. Datos del plan
    BEGIN
        SELECT price, maxProfiles INTO v_price, v_max
        FROM   plans
        WHERE  planId = p_plan_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20004, 'El plan no existe: ' || p_plan_id);
    END;

    -- 3. Sin períodos superpuestos
    SELECT COUNT(*) INTO v_overlaps
    FROM   subscriptions
    WHERE  accountId = p_account_id
    AND    startsAt < v_end
    AND    endsAt   > v_start;

    IF v_overlaps > 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'La cuenta ya tiene una suscripción vigente o con período superpuesto');
    END IF;

    -- 4. Perfiles activos <= máximo del nuevo plan
    SELECT COUNT(*) INTO v_active
    FROM   profiles
    WHERE  accountId = p_account_id
    AND    isActive = 'Y';

    IF v_active > v_max THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Hay ' || v_active || ' perfiles activos y el plan admite ' || v_max ||
            '. Desactive los excedentes antes de contratar');
    END IF;

    -- 5. Suscripción y pago (los dos o ninguno)
    INSERT INTO subscriptions (accountId, planId, startsAt, endsAt)
    VALUES (p_account_id, p_plan_id, v_start, v_end)
    RETURNING subscriptionId INTO p_subscription_id;

    INSERT INTO payments (subscriptionId, paidAt, amount, reference)
    VALUES (p_subscription_id, v_start, v_price, p_reference);

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO sp_contract;
        p_subscription_id := NULL;
        RAISE;
END sp_contract_subscription;
